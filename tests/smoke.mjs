import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
await p.goto('http://localhost:3000');
await p.fill('#nameInput', '本地测试');
await p.click('#createBtn');
await p.waitForSelector('#lobbyScreen.on', { timeout: 8000 });
const code = (await p.locator('#roomCode').textContent()).trim();
console.log('本地建房成功，房间号:', code, '| 顶部状态:', await p.locator('#dayChip').textContent());
await p.screenshot({ path: 'shots/local-lobby.png' });
await p.click('#readyBtn');
await p.click('#startBtn');
await p.waitForTimeout(2500);
console.log('进入对局:', await p.locator('#gameScreen.on').count(), '| 阶段:', await p.locator('#tableLabel').textContent());
await p.screenshot({ path: 'shots/local-game.png' });
console.log('页面错误:', errs.length ? errs : '无');
await b.close();
